export const translations: Record<Lang, Dict> = { en, de, zh };
export type Translations = Dict;

/** Renders one structured match reason as a sentence in the given language. */
export function reasonText(reason: Reason, lang: Lang, tagFor: (a: Affinity) => string): string {
  const t = translations[lang];
  switch (reason.code) {
    case "topics": {
      const list = reason.topics.map((topic) => t.topics[topic]);
      const joiner = lang === "en" ? " and " : lang === "de" ? " und " : "、";
      const text =
        list.length > 1
          ? list.slice(0, -1).join(lang === "zh" ? "、" : ", ") + joiner + list[list.length - 1]
          : list[0];
      return t.reasons.topics(text);
    }
    case "affinity":
      return t.reasons.affinity(tagFor(reason.affinity));
    case "excellence":
    case "union":
    case "faith":
    case "firstGen":
    case "neutral":
    case "general":
      return t.reasons[reason.code];
  }
}
